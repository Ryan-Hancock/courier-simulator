// runStats measures the seeded company and writes, for an article folder:
//
//	data/*.csv            the numbers behind every chart
//	visuals/*.svg         static charts for Medium
//	data/measured.md      headline numbers to quote
//
// Articles only quote what this command measured.
func runStats(ctx context.Context, args []string) error {
	fs := flag.NewFlagSet("stats", flag.ExitOnError)
	out := fs.String("out", "articles/00-skeleton", "article folder")
	fs.Parse(args)
	for _, d := range []string{"data", "visuals"} {
		if err := os.MkdirAll(filepath.Join(*out, d), 0o755); err != nil {
			return err
		}
	}
	pool, err := dbx.Connect(ctx, dbx.URL())
	if err != nil {
		return err
	}
	defer pool.Close()

	query := func(sql string) ([][]string, error) {
		rows, err := pool.Query(ctx, sql)
		if err != nil {
			return nil, err
		}
		defer rows.Close()
		var out [][]string
		for rows.Next() {
			vals, err := rows.Values()
			if err != nil {
				return nil, err
			}
			rec := make([]string, len(vals))
			for i, v := range vals {
				switch x := v.(type) {
				case time.Time:
					rec[i] = x.Format("2006-01-02")
				default:
					rec[i] = fmt.Sprint(x)
				}
			}
			out = append(out, rec)
		}
		return out, rows.Err()
	}
	writeCSV := func(name string, header []string, rows [][]string) error {
		f, err := os.Create(filepath.Join(*out, "data", name))
		if err != nil {
			return err
		}
		defer f.Close()
		w := csv.NewWriter(f)
		w.Write(header)
		w.WriteAll(rows)
		return w.Error()
	}

	// Daily jobs over the whole history.
	// Closed days (Christmas, New Year) count as zero rather than vanishing.
	daily, err := query(`WITH d AS (SELECT (created_at AT TIME ZONE 'Europe/London')::date AS day, count(*) AS n FROM jobs GROUP BY 1)
		SELECT g::date, coalesce(d.n, 0)
		FROM generate_series((SELECT min(day) FROM d), (SELECT max(day) FROM d), interval '1 day') g
		LEFT JOIN d ON d.day = g::date ORDER BY 1`)
	if err != nil {
		return err
	}
	if err := writeCSV("daily-jobs.csv", []string{"date", "jobs"}, daily); err != nil {
		return err
	}

	// Average bookings per hour on weekdays.
	hourly, err := query(`SELECT extract(hour FROM created_at AT TIME ZONE 'Europe/London')::int AS h,
			round(count(*)::numeric / count(DISTINCT (created_at AT TIME ZONE 'Europe/London')::date), 1)::float8
		FROM jobs WHERE extract(isodow FROM created_at AT TIME ZONE 'Europe/London') <= 5
		GROUP BY 1 HAVING count(*) > 100 ORDER BY 1`)
	if err != nil {
		return err
	}
	if err := writeCSV("weekday-bookings-by-hour.csv", []string{"hour", "avg_jobs"}, hourly); err != nil {
		return err
	}

	// Average jobs by day of week.
	weekday, err := query(`SELECT to_char(d, 'Dy'), round(avg(n))::int FROM (
			SELECT (created_at AT TIME ZONE 'Europe/London')::date AS d, count(*) AS n FROM jobs GROUP BY 1) t
		GROUP BY extract(isodow FROM d), 1 ORDER BY extract(isodow FROM d)`)
	if err != nil {
		return err
	}
	if err := writeCSV("jobs-by-weekday.csv", []string{"weekday", "avg_jobs"}, weekday); err != nil {
		return err
	}

	// Headline numbers.
	head, err := query(`SELECT
		(SELECT count(*) FROM jobs),
		(SELECT count(*) FROM job_events),
		(SELECT count(*) FROM location_pings),
		(SELECT count(*) FROM accounts),
		(SELECT count(*) FROM customers),
		(SELECT count(*) FROM addresses),
		(SELECT count(*) FROM drivers),
		(SELECT count(*) FROM vehicles),
		(SELECT round(100.0 * avg((type = 'failed')::int), 2) FROM job_events WHERE type IN ('delivered', 'failed'))::float8,
		(SELECT round(100.0 * avg((d.first_delivered <= j.window_end)::int), 1) FROM jobs j
			JOIN (SELECT job_id, min(at) AS first_delivered FROM job_events WHERE type = 'delivered' GROUP BY 1) d ON d.job_id = j.id)::float8,
		(SELECT round(avg(price_pence))::float8 FROM jobs WHERE status <> 'cancelled'),
		(SELECT round(avg(n)) FROM (SELECT count(*) n FROM location_pings
			WHERE extract(isodow FROM at AT TIME ZONE 'Europe/London') <= 5
			GROUP BY (at AT TIME ZONE 'Europe/London')::date) p)::bigint,
		(SELECT pg_size_pretty(pg_total_relation_size('location_pings')))`)
	if err != nil {
		return err
	}
	h := head[0]

	peak, normal := peakAndNormal(daily)
	md := fmt.Sprintf(`# Measured numbers

Generated by `+"`geksim stats`"+` on %s. Quote only these.

| Measure | Value |
| --- | --- |
| Jobs in history | %s |
| Job events | %s |
| Business accounts | %s |
| Customers | %s |
| Addresses (real OSM streets) | %s |
| Drivers / vehicles | %s / %s |
| Failed first attempts | %s%% |
| Delivered inside the promised window | %s%% |
| Average price | £%.2f |
| Median weekday jobs, last 8 weeks | %s |
| Busiest day | %s (%s jobs, %.1fx a normal weekday) |
| GPS pings stored | %s |
| GPS pings per weekday | %s |
| location_pings size on disk | %s |
`, time.Now().Format("2006-01-02 15:04"), thousands(atoi(h[0])), thousands(atoi(h[1])), h[3], thousands(atoi(h[4])), thousands(atoi(h[5])), h[6], h[7], h[8], h[9],
		atof(h[10])/100, thousands(normal), peak.date, thousands(peak.n), float64(peak.n)/float64(max(normal, 1)), thousands(atoi(h[2])), thousands(atoi(h[11])), h[12])
	if err := os.WriteFile(filepath.Join(*out, "data", "measured.md"), []byte(md), 0o644); err != nil {
		return err
	}

	// Charts.
	if err := os.WriteFile(filepath.Join(*out, "visuals", "daily-jobs.svg"),
		[]byte(lineChart(daily, "Jobs booked per day", "Every booking in the simulated history. Weekly rhythm, Black Friday and the run-up to Christmas.", peak)), 0o644); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(*out, "visuals", "bookings-by-hour.svg"),
		[]byte(barChart(hourly, "When bookings arrive", "Average jobs booked per hour on a weekday: a morning rush, a lunchtime dip, an afternoon bump", func(s string) string { return s + ":00" })), 0o644); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(*out, "visuals", "jobs-by-weekday.svg"),
		[]byte(barChart(weekday, "Monday is the busiest day", "Average jobs booked per day of the week", func(s string) string { return s })), 0o644); err != nil {
		return err
	}
	fmt.Print(md)
	return nil
}

type dayCount struct {
	date string
	n    int
}

// peakAndNormal returns the busiest day and the median weekday volume over the
// last 8 weeks of history.
func peakAndNormal(daily [][]string) (dayCount, int) {
	var peak dayCount
	for _, r := range daily {
		if n := atoi(r[1]); n > peak.n {
			peak = dayCount{r[0], n}
		}
	}
	var recent []int
	for i := len(daily) - 1; i >= 0 && len(recent) < 40; i-- {
		t, _ := time.Parse("2006-01-02", daily[i][0])
		if wd := t.Weekday(); wd != time.Saturday && wd != time.Sunday {
			recent = append(recent, atoi(daily[i][1]))
		}
	}
	return peak, median(recent)
}

// ---------------------------------------------------------------- SVG charts
//
// Static charts for Medium: light surface, one series in the reference
// categorical slot 1, recessive grid, thin marks, selective labels only.

const (
	chartW, chartH                  = 1000, 520
	padL, padR, padT, padB          = 64, 24, 96, 48
	surface, ink, inkMuted, gridCol = "#fcfcfb", "#0b0b0b", "#52514e", "#e4e3df"
	series1                         = "#2a78d6"
	font                            = "system-ui, -apple-system, 'Segoe UI', sans-serif"
)

func svgOpen(b *strings.Builder, title, subtitle string) {
	fmt.Fprintf(b, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %d %d" width="%d" height="%d" font-family="%s" role="img" aria-label="%s">`,
		chartW, chartH, chartW, chartH, html.EscapeString(font), html.EscapeString(title))
	fmt.Fprintf(b, `<title>%s</title><rect width="100%%" height="100%%" fill="%s"/>`, html.EscapeString(title), surface)
	fmt.Fprintf(b, `<text x="%d" y="40" font-size="22" font-weight="600" fill="%s">%s</text>`, padL, ink, html.EscapeString(title))
	fmt.Fprintf(b, `<text x="%d" y="66" font-size="14" fill="%s">%s</text>`, padL, inkMuted, html.EscapeString(subtitle))
	fmt.Fprintf(b, `<text x="%d" y="%d" font-size="11" fill="%s" text-anchor="end">GekGo is fictional. Data: geksim seed 42.</text>`, chartW-padR, chartH-10, inkMuted)
}

// yAxis draws gridlines at nice steps and returns the y scale.
func yAxis(b *strings.Builder, maxV float64) func(float64) float64 {
	step := niceStep(maxV / 4)
	top := math.Ceil(maxV/step) * step
	y := func(v float64) float64 { return padT + (chartH-padT-padB)*(1-v/top) }
	for v := 0.0; v <= top+step/2; v += step {
		fmt.Fprintf(b, `<line x1="%d" x2="%d" y1="%.1f" y2="%.1f" stroke="%s" stroke-width="1"/>`, padL, chartW-padR, y(v), y(v), gridCol)
		fmt.Fprintf(b, `<text x="%d" y="%.1f" font-size="12" fill="%s" text-anchor="end" dominant-baseline="middle">%s</text>`, padL-8, y(v), inkMuted, thousands(int(v)))
	}
	return y
}

func lineChart(rows [][]string, title, subtitle string, peak dayCount) string {
	var b strings.Builder
	svgOpen(&b, title, subtitle)
	maxV := 0.0
	for _, r := range rows {
		maxV = math.Max(maxV, atof(r[1]))
	}
	y := yAxis(&b, maxV)
	n := len(rows)
	x := func(i int) float64 { return padL + float64(chartW-padL-padR)*float64(i)/float64(max(n-1, 1)) }

	// Month ticks on the first of each quarter month.
	for i, r := range rows {
		if strings.HasSuffix(r[0], "-01") {
			t, _ := time.Parse("2006-01-02", r[0])
			if (t.Month()-1)%3 == 0 {
				fmt.Fprintf(&b, `<text x="%.1f" y="%d" font-size="12" fill="%s" text-anchor="middle">%s</text>`, x(i), chartH-padB+20, inkMuted, t.Format("Jan 2006"))
				fmt.Fprintf(&b, `<line x1="%.1f" x2="%.1f" y1="%d" y2="%d" stroke="%s"/>`, x(i), x(i), chartH-padB, chartH-padB+5, inkMuted)
			}
		}
	}
	var pts []string
	peakI := 0
	for i, r := range rows {
		pts = append(pts, fmt.Sprintf("%.1f,%.1f", x(i), y(atof(r[1]))))
		if r[0] == peak.date {
			peakI = i
		}
	}
	fmt.Fprintf(&b, `<polyline points="%s" fill="none" stroke="%s" stroke-width="1.5" stroke-linejoin="round"/>`, strings.Join(pts, " "), series1)

	// Label the busiest day and Black Friday only.
	label := func(i int, text string, dy float64, left bool) {
		px, py := x(i), y(atof(rows[i][1]))
		fmt.Fprintf(&b, `<circle cx="%.1f" cy="%.1f" r="4" fill="%s" stroke="%s" stroke-width="2"/>`, px, py, series1, surface)
		anchor, tx := "start", px+10
		if left {
			anchor, tx = "end", px-10
		}
		fmt.Fprintf(&b, `<text x="%.1f" y="%.1f" font-size="13" fill="%s" text-anchor="%s">%s</text>`, tx, py+dy, ink, anchor, html.EscapeString(text))
	}
	t, _ := time.Parse("2006-01-02", peak.date)
	label(peakI, fmt.Sprintf("%s: %s jobs", t.Format("Mon 2 Jan 2006"), thousands(peak.n)), 4, false)
	for i, r := range rows {
		t, _ := time.Parse("2006-01-02", r[0])
		if t.Month() == time.November && t.Weekday() == time.Friday && t.Day() >= 22 && t.Day() <= 28 && i != peakI {
			label(i, fmt.Sprintf("Black Friday %d: %s", t.Year(), thousands(atoi(r[1]))), 4, true)
		}
	}
	b.WriteString(`</svg>`)
	return b.String()
}

func barChart(rows [][]string, title, subtitle string, xLabel func(string) string) string {
	var b strings.Builder
	svgOpen(&b, title, subtitle)
	maxV := 0.0
	for _, r := range rows {
		maxV = math.Max(maxV, atof(r[1]))
	}
	y := yAxis(&b, maxV)
	n := len(rows)
	slot := float64(chartW-padL-padR) / float64(n)
	bw := math.Min(slot-2, slot*0.62) // leave a surface gap between bars
	for i, r := range rows {
		v := atof(r[1])
		cx := padL + slot*(float64(i)+0.5)
		top, base := y(v), y(0)
		// 4px rounded data-end, square at the baseline.
		rad := math.Min(4, (base-top)/2)
		fmt.Fprintf(&b, `<path d="M%.1f,%.1f V%.1f Q%.1f,%.1f %.1f,%.1f H%.1f Q%.1f,%.1f %.1f,%.1f V%.1f Z" fill="%s"><title>%s: %s</title></path>`,
			cx-bw/2, base, top+rad, cx-bw/2, top, cx-bw/2+rad, top, cx+bw/2-rad, cx+bw/2, top, cx+bw/2, top+rad, base, series1,
			html.EscapeString(xLabel(r[0])), r[1])
		fmt.Fprintf(&b, `<text x="%.1f" y="%d" font-size="12" fill="%s" text-anchor="middle">%s</text>`, cx, chartH-padB+20, inkMuted, html.EscapeString(xLabel(r[0])))
	}
	b.WriteString(`</svg>`)
	return b.String()
}

// ---------------------------------------------------------------- small helpers

func niceStep(raw float64) float64 {
	if raw <= 0 {
		return 1
	}
	mag := math.Pow(10, math.Floor(math.Log10(raw)))
	for _, m := range []float64{1, 2, 2.5, 5, 10} {
		if m*mag >= raw {
			return m * mag
		}
	}
	return 10 * mag
}

func thousands(n int) string {
	s := strconv.Itoa(n)
	for i := len(s) - 3; i > 0; i -= 3 {
		s = s[:i] + "," + s[i:]
	}
	return s
}

func atoi(s string) int     { n, _ := strconv.Atoi(s); return n }
func atof(s string) float64 { f, _ := strconv.ParseFloat(s, 64); return f }

func median(xs []int) int {
	if len(xs) == 0 {
		return 0
	}
	s := append([]int(nil), xs...)
	for i := 1; i < len(s); i++ {
		for j := i; j > 0 && s[j] < s[j-1]; j-- {
			s[j], s[j-1] = s[j-1], s[j]
		}
	}
	return s[len(s)/2]
}
